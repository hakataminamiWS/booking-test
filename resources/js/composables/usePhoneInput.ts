            // 'DE' -> 2桁? 'CDE' -> 3桁? 
            // マップ定義を見ると '120': 'DEF' (3文字) -> フリーダイヤル 0120-xxx-xxx (3桁-3桁?)
            // '3': 'BCDE' (4文字) -> 東京 03-xxxx-xxxx (2桁-4桁?)
